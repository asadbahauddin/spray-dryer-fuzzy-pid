function f = fig_new(width_cm, height_cm)
%FIG_NEW  Figure with journal-consistent size and fonts (>= 9 pt).
if nargin < 1, width_cm = 17; end
if nargin < 2, height_cm = 9; end
f = figure('Visible','off','Units','centimeters', ...
    'Position',[2 2 width_cm height_cm],'Color','w', ...
    'PaperUnits','centimeters','PaperSize',[width_cm height_cm]);
set(f,'DefaultAxesFontSize',9,'DefaultTextFontSize',9, ...
    'DefaultAxesFontName','Helvetica','DefaultLineLineWidth',1.1, ...
    'DefaultAxesBox','on','DefaultAxesXGrid','on','DefaultAxesYGrid','on', ...
    'DefaultLegendFontSize',8.5,'DefaultAxesTitleFontWeight','normal');
end
